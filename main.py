#
# POST Method
# End Point: /created_note
#
# [DESCRIPTION]
#  Method used for specifying the 'note_new_uri' parameter to receive the created note
#
# [INPUTS] 
#  HTTP request object
# 
# [OUTPUTS]
#  A list of generated notes:
#  [{ "noteid": <Note ID>, "internal_id": <Internal ID> }]
# 
# [NOTES]
#  Update the global variable 'g_LastNoteId'
#  This implementation does not allow multi-user access. 
#  It is better to store the value in any database system.
#
@app.post("/created_note")
async def getNote(request: Request): 
    global g_LastNoteId

    results = await request.json()
    if is_reload_enabled():
        print("[Created Note]", results)
    if len(results) > 0:
        g_LastNoteId = results[0]['noteid']
    return results
