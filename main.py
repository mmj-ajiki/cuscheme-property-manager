#
# GET Method
# End Point: /open
#
# [DESCRIPTION]
#  Open the last created note
#
# [INPUTS] 
#  HTTP request object
# 
# [OUTPUTS]
#  Response for an HTML template to be renderred
# 
# [NOTES]
#  Open templates/open_<appLang>.html
#
#  A note is opened by the following custom URL:
#   gembanotech6:///nsk/open?access_id=<Access ID>&
#       access_token=<Access Token>&
#       note_uri=<Last Created Note ID>
#
@app.get("/open", response_class=HTMLResponse)
async def openLastNote(request: Request):
    para = "?"

    # Access ID and Token are temporarily set
    para += 'access_id=' + accessId + '&access_token=' + accessToken
    # note_uri (to open the created note) 
    if g_LastNoteId != None:
        para += '&note_uri=' + urllib.parse.quote(g_LastNoteId)

    targetPage = "open_" + appLang + ".html"
    
    return templates.TemplateResponse(targetPage, {"request": request, "protocol": uriScheme, "parameters": para, "note_id": g_LastNoteId})
