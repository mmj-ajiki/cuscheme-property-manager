#
# GET Method
# End Point: /recordset
#
# [DESCRIPTION]
#  Get a set of records of property elements from the CSV file
#
# [INPUTS] 
#  HTTP request object
# 
# [OUTPUTS]
#  A list of properties:
#  [{'Name':<Property Name1>, 'Type':<Property Type1>, 'Price': <Price1>, 'Address': <Address1>},{...},...]
# 
# [NOTES]
#
@app.get("/recordset")
def getRecordSet():
    output = []
    # Read a CSV file
    skip = True
    with open(csvFile, encoding="utf-8") as f:
        reader = csv.reader(f, delimiter=',')
        for row in reader:
            if skip == False:
                json = {'Name':row[0], 'Type':row[1], 'Price':row[2], 'Address':row[3]}
                output.append(json)
            else:
                skip = False # Skip the first row
    
    if is_reload_enabled():
        print(output)

    return output
